#!/usr/bin/env node
/**
 * 读 src/shared/tokens.data.json → 生成 src/renderer/styles/tokens.css。
 * 生成的变量必须与 src/shared/tokens.ts 的 themeToCssVars(deepSpace) 完全一致
 * （E-THEME-002：数量 != 期望数量 → 构建期失败）。
 *
 * 为什么读 JSON 而不是 import tokens.ts：Node 20 不能直接 import .ts。
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'src/shared/tokens.data.json');
const OUT = join(ROOT, 'src/renderer/styles/tokens.css');

const raw = JSON.parse(readFileSync(DATA, 'utf8'));
const theme = raw.deepSpace;
if (!theme) {
  console.error('FATAL: tokens.data.json 缺少 deepSpace');
  process.exit(1);
}

const kebab = (k) => k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

const vars = [];
const push = (k, v) => vars.push([`--ark-${k}`, String(v)]);

for (const [k, v] of Object.entries(theme.color)) push(kebab(k), v);
for (const [k, v] of Object.entries(theme.radius)) push(`radius-${kebab(k)}`, `${v}px`);
theme.space.forEach((v, i) => push(`space-${i + 1}`, `${v}px`));
for (const [k, v] of Object.entries(theme.type)) {
  push(`font-${kebab(k)}-size`, `${v.size}px`);
  push(`font-${kebab(k)}-weight`, v.weight);
  push(`font-${kebab(k)}-line-height`, v.lineHeight);
}
for (const [k, v] of Object.entries(theme.shadow)) push(`shadow-${kebab(k)}`, v);
push('motion-fast', `${theme.motion.fast}ms`);
push('motion-base', `${theme.motion.base}ms`);
push('motion-slow', `${theme.motion.slow}ms`);
push('motion-spring', theme.motion.spring);
push('surface-blur', `${theme.surfaceBlur}px`);

// 断言：与 themeToCssVars 的期望条数一致（此处独立按同一规则计数，防止两边漂移）
const expectedCount = Object.keys(theme.color).length
  + Object.keys(theme.radius).length
  + theme.space.length
  + Object.keys(theme.type).length * 3
  + Object.keys(theme.shadow).length
  + 4   // motion fast/base/slow/spring
  + 1;  // surfaceBlur
if (vars.length !== expectedCount) {
  console.error(`FATAL: token 变量数 ${vars.length} != 期望 ${expectedCount}`);
  process.exit(1);
}
if (vars.length < 8) {
  console.error(`FATAL: token 变量数 ${vars.length} < 8（ACCEPT A9）`);
  process.exit(1);
}

const lines = [
  '/* AUTO-GENERATED by scripts/gen-tokens.mjs. DO NOT EDIT. */',
  ':root {',
  ...vars.map(([k, v]) => `  ${k}: ${v};`),
  '}',
  '',
];

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(`tokens.css 生成完成：${vars.length} 个 --ark-* 变量 → ${OUT}`);
